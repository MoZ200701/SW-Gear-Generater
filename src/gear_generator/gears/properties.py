"""The custom properties a built part carries, so a bill of materials can list the gear.

Only once probe custom_properties has passed (``findings.CUSTOM_PROPERTY_ROUTE``):
until then no plan has any, and a part is built exactly as before. The sizes
are stamped only if a property naming a global was seen to follow it
(``findings.PROPERTY_LINKS_GLOBALS``) — a size written as plain text would be
wrong the first time ``"No. of Teeth"`` was edited — so they are always the
globals' own quoted names, and the words are the things a rebuild cannot change.
"""

from __future__ import annotations

from typing import List

from .. import __version__, findings
from . import equations
from .base import CustomProperty

KIND_WORDS = {"spur": "Spur", "helical": "Helical", "herringbone": "Herringbone", "bevel": "Straight bevel"}
FLANK_WORDS = {"A": "involute", "B": "arc"}


def property_ops(kind: str, recipe: str, internal: bool, sizes: List[str]) -> List[CustomProperty]:
    """``Description``, ``Gear Kind``, ``Flank`` and ``Generated By``; and, linked, each global in ``sizes``."""
    if findings.CUSTOM_PROPERTY_ROUTE is None:
        return []
    what = KIND_WORDS.get(kind, kind.title())
    noun = "ring gear" if internal else "gear"
    ops = [
        CustomProperty("Description", f"{what} {noun}, {FLANK_WORDS.get(recipe, recipe)} flank"),
        CustomProperty("Gear Kind", f"{kind} internal" if internal else kind),
        CustomProperty("Flank", FLANK_WORDS.get(recipe, recipe)),
        CustomProperty("Generated By", f"Gear Generator {__version__}"),
    ]
    if findings.PROPERTY_LINKS_GLOBALS:
        ops.extend(CustomProperty(name, equations.quote(name)) for name in sizes)
    return ops
