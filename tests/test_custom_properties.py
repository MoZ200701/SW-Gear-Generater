"""Custom properties on a built part — none until the custom_properties probe has settled them.

Nothing here has run on SolidWorks. What is pinned is that an unprobed build is
exactly what it was, and what a probed one would stamp, in what order.
"""

import pytest

from gear_generator import findings, swbuild
from gear_generator.gears import kind_for
from gear_generator.gears.base import CustomProperty, ManualStep
from gear_generator.probe import decide
from gear_generator.spec import GearSpec

from test_swbuild import FakeSolidWorks, never_exists

SPECS = [
    GearSpec(),
    GearSpec(module="2", teeth="15", profile_shift="0.12"),
    GearSpec(kind="helical", module="2", teeth="20", helix_angle="15", face_width="20"),
    GearSpec(kind="herringbone", module="2", teeth="20", helix_angle="30", face_width="24"),
    GearSpec(module="2", teeth="60", teeth_side="internal"),
    GearSpec(kind="helical", module="2", teeth="60", helix_angle="15", teeth_side="internal"),
    GearSpec(kind="bevel", module="3", teeth="20", mate_teeth="40", face_width="20"),
]


def _plan(spec):
    kind = kind_for(spec)
    return kind.plan(spec, kind.derive(spec), kind.recipe_for(spec), "", r"C:\Gears\Part.SLDPRT")


def _props(plan):
    return [(op.name, op.value) for op in plan.ops if isinstance(op, CustomProperty)]


@pytest.fixture
def settled(monkeypatch):
    for name, value in (("CUSTOM_PROPERTY_ROUTE", "Add3"), ("CUSTOM_INFO_TEXT", 30), ("CUSTOM_PROPERTY_REPLACE", 1),
                        ("PROPERTY_READ_ROUTE", "Get6 with by-reference outs"), ("PROPERTY_LINKS_GLOBALS", False)):
        monkeypatch.setattr(findings, name, value)


@pytest.mark.parametrize("spec", SPECS, ids=lambda s: f"{s.kind}-{s.teeth_side}")
def test_until_the_probe_has_run_no_part_carries_a_property(spec):
    assert findings.CUSTOM_PROPERTY_ROUTE is None
    assert _props(_plan(spec)) == []


@pytest.mark.parametrize("spec", SPECS, ids=lambda s: f"{s.kind}-{s.teeth_side}")
def test_once_settled_every_kind_says_what_it_is_before_the_material_step(settled, spec):
    plan = _plan(spec)
    assert plan.check() == []
    names = [name for name, _ in _props(plan)]
    assert names == ["Description", "Gear Kind", "Flank", "Generated By"]
    ops = list(plan.ops)
    last = max(i for i, op in enumerate(ops) if isinstance(op, CustomProperty))
    assert isinstance(ops[last + 1], ManualStep)


def test_the_words_are_what_a_rebuild_cannot_change(settled):
    assert _props(_plan(SPECS[0]))[:3] == [("Description", "Spur gear, involute flank"), ("Gear Kind", "spur"),
                                           ("Flank", "involute")]
    assert _props(_plan(SPECS[4]))[:2] == [("Description", "Spur ring gear, involute flank"),
                                           ("Gear Kind", "spur internal")]


def test_sizes_are_stamped_only_linked_to_their_globals(settled, monkeypatch):
    monkeypatch.setattr(findings, "PROPERTY_LINKS_GLOBALS", True)
    sizes = dict(_props(_plan(SPECS[1])))
    assert sizes["No. of Teeth"] == '"No. of Teeth"' and sizes["Profile Shift"] == '"Profile Shift"'
    assert "Helix Angle" in dict(_props(_plan(SPECS[2])))
    ring = dict(_props(_plan(SPECS[4])))
    assert "Inner Diameter" in ring and "Rim Diameter" in ring and "Outer Diameter" not in ring
    bevel = dict(_props(_plan(SPECS[6])))
    assert bevel["Mate Teeth"] == '"Mate Teeth"' and bevel["Shaft Angle"] == '"Shaft Angle"'
    # Every linked name is a global the part has.
    for spec in SPECS:
        plan = _plan(spec)
        names = {op.name for op in plan.globals()}
        assert {v.strip('"') for n, v in _props(plan) if v.startswith('"')} <= names, spec


def test_a_settled_build_stamps_them_against_the_fake(settled):
    fake = FakeSolidWorks()
    result = swbuild.build(fake, _plan(SPECS[0]), never_exists)
    assert result.ok, result.log_lines()
    stamped = [args for name, args in fake.calls if name == "set_custom_property"]
    assert stamped[0] == ("Description", "Spur gear, involute flank")
    assert "ok      property 'Generated By'" in result.log_lines()


def test_the_decisions_come_only_from_a_passing_probe():
    facts = {"custom_info_text": 30, "custom_property_replace": 1, "property_read_route": "Get",
             "property_links_global": True}
    passed = decide.decide({"custom_properties": {"status": "pass", "facts": facts}})
    assert (passed["custom_property_route"], passed["custom_info_text"], passed["property_links_globals"]) == \
        ("Add3", 30, True)
    failed = decide.decide({"custom_properties": {"status": "fail", "facts": facts}})
    assert failed["custom_property_route"] is None and failed["property_links_globals"] is None
